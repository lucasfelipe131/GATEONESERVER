// Formulário de captação com auto-geração de ID para novos clientes
import CustomerIDGenerator from './customer-id-generator.js';

export function initializeCaptureForm() {
  const captureForm = document.querySelector('form[data-form="capture"]') || createCaptureForm();

  // Botão para gerar ID automático
  const generateIDButton = captureForm.querySelector('[data-action="generate-id"]');
  if (generateIDButton) {
    generateIDButton.addEventListener('click', async (e) => {
      e.preventDefault();
      await generateAndFillID(captureForm);
    });
  }

  // Auto-preencher ID ao focar no campo (opcional)
  const idField = captureForm.querySelector('[name="bitpanel_list_id"]');
  if (idField) {
    idField.addEventListener('focus', async (e) => {
      if (!e.target.value) {
        const suggestion = CustomerIDGenerator.generateNanoID();
        e.target.placeholder = `Sugestão: ${suggestion}`;
      }
    });
  }

  return captureForm;
}

async function generateAndFillID(form) {
  const idField = form.querySelector('[name="bitpanel_list_id"]');
  const generateButton = form.querySelector('[data-action="generate-id"]');

  if (!idField) return;

  generateButton.disabled = true;
  generateButton.textContent = 'Gerando...';

  try {
    // Tenta gerar um ID único (chamando a API)
    const response = await fetch('/api/admin/generate-customer-id', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({ format: 'nano' })
    });

    if (!response.ok) {
      throw new Error('Falha ao gerar ID');
    }

    const { id, format } = await response.json();
    idField.value = id;
    idField.dataset.format = format;
    idField.dataset.autoGenerated = 'true';

    // Feedback visual
    idField.classList.add('auto-generated');
    setTimeout(() => idField.classList.remove('auto-generated'), 2000);
  } catch (error) {
    console.error('Erro ao gerar ID:', error);
    // Fallback: gera localmente se a API falhar
    const fallbackID = CustomerIDGenerator.generateNanoID();
    idField.value = fallbackID;
    idField.dataset.autoGenerated = 'fallback';
  } finally {
    generateButton.disabled = false;
    generateButton.textContent = '🔄 Gerar ID';
  }
}

function createCaptureForm() {
  const form = document.createElement('form');
  form.dataset.form = 'capture';
  form.className = 'customer-capture-form';
  form.innerHTML = `
    <fieldset>
      <legend>Cadastro de novo cliente</legend>

      <div class="form-group">
        <label for="capture-name">Nome do cliente *</label>
        <input type="text" id="capture-name" name="name" required />
      </div>

      <div class="form-group">
        <label for="capture-whatsapp">WhatsApp *</label>
        <input type="tel" id="capture-whatsapp" name="whatsapp" placeholder="55DDD9XXXXXXXX" required />
      </div>

      <div class="form-group">
        <label for="capture-plan">Plano *</label>
        <select id="capture-plan" name="plan" required>
          <option value="">Selecione</option>
          <option value="monthly">Mensal (R$ 30)</option>
          <option value="quarterly">Trimestral (R$ 85)</option>
          <option value="semi_annual">Semestral (R$ 150)</option>
          <option value="annual">Anual (R$ 270)</option>
        </select>
      </div>

      <div class="form-group">
        <label for="capture-id">ID BitPanel</label>
        <div class="input-group">
          <input type="text" id="capture-id" name="bitpanel_list_id" placeholder="Deixe em branco para auto-gerar" />
          <button type="button" class="btn btn-small btn-secondary" data-action="generate-id">🔄 Gerar ID</button>
        </div>
        <small>Se deixado em branco, um ID será gerado automaticamente</small>
      </div>

      <div class="form-group">
        <label for="capture-reference">Usuário BitPanel</label>
        <input type="text" id="capture-reference" name="bitpanel_reference" placeholder="usuario-painel" />
      </div>

      <div class="form-group">
        <label for="capture-consent">
          <input type="checkbox" id="capture-consent" name="consent_contact" />
          Autorizo contato para promoções e atualizações
        </label>
      </div>

      <button type="submit" class="btn btn-primary">Cadastrar cliente</button>
    </fieldset>
  `;

  form.addEventListener('submit', handleCaptureSubmit);
  return form;
}

async function handleCaptureSubmit(e) {
  e.preventDefault();

  const formData = new FormData(e.target);
  const data = Object.fromEntries(formData);

  // Se o ID não foi preenchido manualmente, gera automaticamente
  if (!data.bitpanel_list_id || data.bitpanel_list_id.trim() === '') {
    const idResult = await fetch('/api/admin/generate-customer-id', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin'
    }).then(r => r.json()).catch(() => ({ id: CustomerIDGenerator.generateNanoID() }));
    data.bitpanel_list_id = idResult.id;
  }

  try {
    const response = await fetch('/api/admin/customers', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify(data)
    });

    if (!response.ok) {
      const error = await response.json();
      throw new Error(error.message || 'Erro ao cadastrar cliente');
    }

    alert('✅ Cliente cadastrado com sucesso!');
    e.target.reset();
  } catch (error) {
    alert(`❌ Erro: ${error.message}`);
  }
}

export default initializeCaptureForm;
